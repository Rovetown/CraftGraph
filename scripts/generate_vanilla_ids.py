def main() -> None:
    # Vanilla: lowercase, sorted, deduplicated
    vanilla_sorted = sorted({vid.lower() for vid in _VANILLA_IDS})

    _VANILLA_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    _VANILLA_OUTPUT.write_text(
        "\n".join(vanilla_sorted) + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(vanilla_sorted)} vanilla item IDs to {_VANILLA_OUTPUT}")

    # Mod-compat: preserve original casing, sorted case-insensitively
    mod_sorted = sorted(_MOD_COMPAT_IDS, key=str.lower)

    _MOD_COMPAT_OUTPUT.write_text(
        "\n".join(mod_sorted) + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(mod_sorted)} mod-compat item IDs to {_MOD_COMPAT_OUTPUT}")


if __name__ == "__main__":
    main()
